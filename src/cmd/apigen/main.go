package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	appgraphql "github.com/apimgr/search/src/graphql"
	"github.com/apimgr/search/src/swagger"
	graphql "github.com/graphql-go/graphql"
	"github.com/graphql-go/graphql/language/parser"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, "API generation failed:", err)
		os.Exit(1)
	}
}

func generate() error {
	root, err := os.Getwd()
	if err != nil {
		return err
	}
	if err := appgraphql.InitSchema(); err != nil {
		return fmt.Errorf("initialize GraphQL schema: %w", err)
	}
	spec, err := json.MarshalIndent(swagger.GenerateSpec(nil, "https://generated.invalid"), "", "  ")
	if err != nil {
		return fmt.Errorf("marshal OpenAPI: %w", err)
	}
	if err := writeFile(filepath.Join(root, "src/swagger/openapi.json"), append(spec, '\n')); err != nil {
		return err
	}
	sdl, err := graphQLSDL(&appgraphql.Schema)
	if err != nil {
		return err
	}
	if _, err := parser.Parse(parser.ParseParams{Source: sdl}); err != nil {
		return fmt.Errorf("validate generated GraphQL SDL: %w", err)
	}
	generated := "// Code generated by src/cmd/apigen; DO NOT EDIT.\n\npackage graphql\n\nconst GeneratedSchemaSDL = " + strconv.Quote(sdl) + "\n"
	formatted, err := format.Source([]byte(generated))
	if err != nil {
		return fmt.Errorf("format generated GraphQL source: %w", err)
	}
	return writeFile(filepath.Join(root, "src/graphql/schema_generated.go"), formatted)
}

func writeFile(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

func graphQLSDL(schema *graphql.Schema) (string, error) {
	if schema == nil || schema.QueryType() == nil {
		return "", fmt.Errorf("GraphQL schema has no query root")
	}
	var output bytes.Buffer
	output.WriteString("schema {\n  query: " + schema.QueryType().Name() + "\n")
	if mutation := schema.MutationType(); mutation != nil {
		output.WriteString("  mutation: " + mutation.Name() + "\n")
	}
	if subscription := schema.SubscriptionType(); subscription != nil {
		output.WriteString("  subscription: " + subscription.Name() + "\n")
	}
	output.WriteString("}\n\n")

	typeNames := make([]string, 0, len(schema.TypeMap()))
	for name := range schema.TypeMap() {
		if !strings.HasPrefix(name, "__") {
			typeNames = append(typeNames, name)
		}
	}
	sort.Strings(typeNames)
	for _, name := range typeNames {
		typeDef := schema.Type(name)
		if err := appendType(&output, typeDef); err != nil {
			return "", fmt.Errorf("render GraphQL type %s: %w", name, err)
		}
	}
	for _, directive := range schema.Directives() {
		appendDescription(&output, directive.Description)
		output.WriteString("directive @" + directive.Name + renderArguments(directive.Args) + " on " + strings.Join(directive.Locations, " | ") + "\n\n")
	}
	return output.String(), nil
}

func appendType(output *bytes.Buffer, typeDef graphql.Type) error {
	switch current := typeDef.(type) {
	case *graphql.Scalar:
		if isBuiltInScalar(current.Name()) {
			return nil
		}
		appendDescription(output, current.Description())
		output.WriteString("scalar " + current.Name() + "\n\n")
	case *graphql.Object:
		appendDescription(output, current.Description())
		output.WriteString("type " + current.Name())
		interfaces := current.Interfaces()
		if len(interfaces) > 0 {
			names := make([]string, 0, len(interfaces))
			for _, iface := range interfaces {
				names = append(names, iface.Name())
			}
			sort.Strings(names)
			output.WriteString(" implements " + strings.Join(names, " & "))
		}
		output.WriteString(" {\n")
		fields := current.Fields()
		fieldNames := make([]string, 0, len(fields))
		for fieldName := range fields {
			fieldNames = append(fieldNames, fieldName)
		}
		sort.Strings(fieldNames)
		for _, fieldName := range fieldNames {
			field := fields[fieldName]
			appendIndentedDescription(output, field.Description, 2)
			fmt.Fprintf(output, "  %s%s: %s\n", fieldName, renderArguments(field.Args), field.Type.String())
		}
		output.WriteString("}\n\n")
	case *graphql.InputObject:
		appendDescription(output, current.Description())
		output.WriteString("input " + current.Name() + " {\n")
		fields := current.Fields()
		fieldNames := make([]string, 0, len(fields))
		for fieldName := range fields {
			fieldNames = append(fieldNames, fieldName)
		}
		sort.Strings(fieldNames)
		for _, fieldName := range fieldNames {
			field := fields[fieldName]
			appendIndentedDescription(output, field.Description(), 2)
			fmt.Fprintf(output, "  %s: %s\n", fieldName, field.Type.String())
		}
		output.WriteString("}\n\n")
	case *graphql.Enum:
		appendDescription(output, current.Description())
		output.WriteString("enum " + current.Name() + " {\n")
		values := append([]*graphql.EnumValueDefinition(nil), current.Values()...)
		sort.Slice(values, func(i, j int) bool { return values[i].Name < values[j].Name })
		for _, value := range values {
			appendIndentedDescription(output, value.Description, 2)
			output.WriteString("  " + value.Name + "\n")
		}
		output.WriteString("}\n\n")
	case *graphql.Union:
		appendDescription(output, current.Description())
		output.WriteString("union " + current.Name() + " = ")
		types := current.Types()
		names := make([]string, 0, len(types))
		for _, object := range types {
			names = append(names, object.Name())
		}
		sort.Strings(names)
		output.WriteString(strings.Join(names, " | ") + "\n\n")
	case *graphql.Interface:
		appendDescription(output, current.Description())
		output.WriteString("interface " + current.Name() + " {\n")
		fields := current.Fields()
		fieldNames := make([]string, 0, len(fields))
		for fieldName := range fields {
			fieldNames = append(fieldNames, fieldName)
		}
		sort.Strings(fieldNames)
		for _, fieldName := range fieldNames {
			field := fields[fieldName]
			appendIndentedDescription(output, field.Description, 2)
			fmt.Fprintf(output, "  %s%s: %s\n", fieldName, renderArguments(field.Args), field.Type.String())
		}
		output.WriteString("}\n\n")
	case *graphql.List, *graphql.NonNull:
		return nil
	default:
		return fmt.Errorf("unsupported GraphQL type %T", typeDef)
	}
	return nil
}

func renderArguments(args []*graphql.Argument) string {
	if len(args) == 0 {
		return ""
	}
	args = append([]*graphql.Argument(nil), args...)
	sort.Slice(args, func(i, j int) bool { return args[i].Name() < args[j].Name() })
	parts := make([]string, 0, len(args))
	for _, arg := range args {
		parts = append(parts, arg.Name()+": "+arg.Type.String())
	}
	return "(" + strings.Join(parts, ", ") + ")"
}

func appendDescription(output *bytes.Buffer, description string) {
	if description != "" {
		output.WriteString(strconv.Quote(description) + "\n")
	}
}

func appendIndentedDescription(output *bytes.Buffer, description string, indent int) {
	if description != "" {
		output.WriteString(strings.Repeat(" ", indent) + strconv.Quote(description) + "\n")
	}
}

func isBuiltInScalar(name string) bool {
	switch name {
	case "String", "Boolean", "Int", "Float", "ID":
		return true
	}
	return false
}
